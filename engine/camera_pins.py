"""PlateTrack-style manual corner pins for a bounded streaming stabilizer.

PlateTrack upstream tracker.py uses keyframes as hard corner constraints and
blends tracked->pinned corner residual over PIN_BLEND_FRAMES=10.
This streaming adaptation preserves those principles without buffering frames.

REQUIREMENT: Each pin describes the same fixed *physical* background region,
with four vertices in original top-left / top-right / bottom-right / bottom-left
order. This is NOT multi-region reidentification or automatic zoom recovery.

Untracked gaps are explicitly marked manual_interpolated with confidence 0,
never masquerading as optical-flow detections. Only an explicit manual
correction at that exact frame permits bridging a small gap (<= 8 frames).
"""
import math
import numpy as np

PIN_BLEND_FRAMES=10
MAX_MANUAL_GAP=8

def checked_quad(shape,fx=1.,fy=1.):
    if not isinstance(shape,dict) or not shape.get("closed"):
        raise ValueError("Se necesita una máscara cerrada de exactamente cuatro puntos.")
    verts=shape.get("vertices",[])
    if len(verts)!=4:
        raise ValueError("Para recuperar la cámara, la máscara necesita exactamente cuatro vértices correspondientes al mismo fondo.")
    q=np.asarray(verts,dtype=np.float64)
    if q.shape!=(4,2) or not np.isfinite(q).all():
        raise ValueError("Los cuatro puntos de la máscara son inválidos.")
    q=q*np.array([fx,fy])
    cross=[]
    for i in range(4):
        ab=q[(i+1)%4]-q[i]
        bc=q[(i+2)%4]-q[(i+1)%4]
        cross.append(float(np.cross(ab,bc)))
    if any(abs(x)<1 for x in cross) or not (all(x>0 for x in cross) or all(x<0 for x in cross)):
        raise ValueError("Los cuatro puntos deben formar un cuadrilátero convexo, sin cruces.")
    return q

def similarity_from_quad(q0,q1,max_residual=4.):
    """Least-squares similarity, preserving all 4 manual corner constraints."""
    q0=np.asarray(q0,dtype=np.float64);q1=np.asarray(q1,dtype=np.float64)
    n=len(q0)
    if n!=4 or q1.shape!=(4,2):
        raise ValueError("Una corrección requiere cuatro esquinas correspondientes.")
    A=np.zeros((2*n,4),dtype=np.float64)
    Y=q1.reshape(-1)
    for i,(x,y) in enumerate(q0):
        A[2*i]=[x,-y,1,0]
        A[2*i+1]=[y,x,0,1]
    coeff,*_=np.linalg.lstsq(A,Y,rcond=None)
    a,b,tx,ty=[float(x) for x in coeff]
    M=np.array([[a,-b,tx],[b,a,ty],[0.,0.,1.]])
    scale=math.hypot(a,b)
    if not .3<=scale<=3.3 or abs(np.linalg.det(M))<1e-8:
        raise ValueError("Zoom de la corrección demasiado extremo.")
    fitted=(M@np.concatenate([q0,np.ones((4,1))],axis=1).T).T[:,:2]
    worst=float(np.linalg.norm(fitted-q1,axis=1).max())
    if worst>max_residual:
        raise ValueError(
          "Los cuatro vértices no corresponden a una misma región rígida (error %.1f px). "
          "Ajustalos en el mismo orden del primer fotograma."%worst)
    return M

def _pose(M,center):
    a,b=float(M[0,0]),float(M[1,0])
    sc=math.hypot(a,b)
    if sc<=0:raise ValueError("Transformación sin escala.")
    c=(M@np.array([center[0],center[1],1.]))[:2]
    return np.array([c[0],c[1],math.atan2(b,a),math.log(sc)],dtype=np.float64)

def _from_pose(p,center):
    x,y,angle,logs=p
    a=math.exp(logs)*math.cos(angle)
    b=math.exp(logs)*math.sin(angle)
    u,v=center
    return np.array([[a,-b,x-a*u+b*v],
                     [b,a,y-b*u-a*v],[0.,0.,1.]],dtype=np.float64)

def _interpolate(A,B,t,center):
    pa=_pose(A,center);pb=_pose(B,center)
    pb[2]=pa[2]+((pb[2]-pa[2]+math.pi)%(2*math.pi)-math.pi)
    return _from_pose(pa*(1-t)+pb*t,center)

def pin_samples(samples,frame,pinned_matrix,original_quad,blend_frames=PIN_BLEND_FRAMES,
                max_gap=MAX_MANUAL_GAP):
    """Return (samples copy to frame-1, statistics). Never mutate caller data.

    An interpolated frame is a human-accepted estimate (not a measurement).
    Samples after the pin are generated by a new locally-seeded LK reference.
    """
    if not samples:
        raise ValueError("No hay muestras previas a la corrección.")
    if frame!=samples[-1]["frame"]:
        raise ValueError("Corregí la máscara en el fotograma exacto donde PlateTrack se detuvo.")
    if frame<=samples[0]["frame"]:
        raise ValueError("La corrección debe ser posterior al primer fotograma.")
    good=[i for i,s in enumerate(samples) if s["frame"]<frame and
          (float(s.get("confidence",0))>=.35 or s.get("manual_pin")) and
          not s.get("needs_correction")]
    if not good:
        raise ValueError("No hay fotogramas anteriores fiables donde anclar la corrección.")
    k=good[-1]
    anchor=samples[k]
    gap=frame-anchor["frame"]-1
    if gap>max_gap:
        raise ValueError("Hay %d cuadros sin referencias válidas. No interpolaré más de %d. "
                         "Hacé una corrección en un fotograma anterior."%(gap,max_gap))
    if gap<0:
        raise ValueError("Intervalo de corrección inválido.")
    original_quad=np.asarray(original_quad,dtype=np.float64)
    center=np.mean(original_quad,axis=0)
    pinned_matrix=np.asarray(pinned_matrix,dtype=np.float64)
    revised=[dict(s) for s in samples[:k+1]]
    # Upstream method: spread corner residual over the preceding 10-frame
    # interval so camera path approaches the hard pin without a new jump.
    predicted=np.asarray(samples[-1]["matrix"],dtype=np.float64)
    corners_from=lambda M:(M@np.column_stack([original_quad,np.ones(4)]).T).T[:,:2]
    delta=corners_from(pinned_matrix)-corners_from(predicted)
    # Clamp absurd manual shape edits rather than generating huge interpolations.
    if np.linalg.norm(delta,axis=1).max()>min(160,0.35*max(1,float(np.linalg.norm(original_quad[0]-original_quad[2])))):
        raise ValueError("La corrección cambia demasiado la región. Usá los mismos cuatro puntos del fondo.")
    begin=max(0,k-blend_frames+1)
    for i in range(begin,k+1):
        r=revised[i]
        if r.get("manual_pin"):
            continue  # Hard constraints stay exact.
        w=(i-begin+1)/(frame-begin+1)
        old=np.asarray(r["matrix"],dtype=np.float64)
        adjusted_corners=corners_from(old)+delta*w
        fixed=similarity_from_quad(original_quad,adjusted_corners,max_residual=4.)
        r["matrix"]=fixed.tolist()
        r["manual_blended"]=True
    # Fill ONLY the formerly untrusted gap via interpolation; mark provenance.
    left=np.asarray(revised[-1]["matrix"],dtype=np.float64)
    for step in range(1,gap+1):
        frame_id=int(anchor["frame"])+step
        blend=step/(gap+1)
        estimated=_interpolate(left,pinned_matrix,blend,center)
        original=next(s for s in samples if s["frame"]==frame_id)
        r=dict(original)
        r["matrix"]=estimated.tolist()
        r["confidence"]=0.
        r["low_confidence"]=True
        r["needs_correction"]=False
        r["manual_interpolated"]=True
        r["ecc_score"]=None
        r["points"]=0
        revised.append(r)
    if len(revised)!=(frame-samples[0]["frame"]):
        raise ValueError("No se pudo reconstruir la secuencia sin huecos.")
    return revised,dict(gap=gap,blend_start=int(samples[begin]["frame"]),pin=int(frame))
